@dataclass(frozen=True)
class Combo:
    """Сочетание симптомов, которое значит больше, чем симптомы по отдельности."""

    symptoms: frozenset[str]
    specialist: str
    bonus: float
    fever: bool = False  # срабатывает только при температуре от 38
    urgent: bool = False
    note: str = ""


def _c(*ids: str) -> frozenset[str]:
    return frozenset(ids)


